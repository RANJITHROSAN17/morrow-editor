// Builds docs/BENCHMARK-COMPARISON.md from the JSON results.
//   benchmarks/results/engines.json   (sandbox, npm run benchmark:engines)
//   benchmarks/results/products.json  (Windows, npm run benchmark:products)
// Sign convention everywhere: "Wrytrove vs X" = (Wrytrove - X) / X x 100.
//   negative = Wrytrove is lower (faster, or uses less memory)
//   positive = Wrytrove is higher (slower, or uses more memory)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { percentDiff } from './shared/stats.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const engines = existsSync(join(here, 'results', 'engines.json'))
  ? JSON.parse(readFileSync(join(here, 'results', 'engines.json'), 'utf8'))
  : null;
const products = existsSync(join(here, 'results', 'products.json'))
  ? JSON.parse(readFileSync(join(here, 'results', 'products.json'), 'utf8'))
  : null;
const outPath = join(here, '..', 'docs', 'BENCHMARK-COMPARISON.md');

const fmtMs = (v) => (v == null ? '—' : v >= 100 ? `${v.toFixed(0)} ms` : v >= 10 ? `${v.toFixed(1)} ms` : `${v.toFixed(2)} ms`);
const fmtMB = (v) => (v == null ? '—' : `${v.toFixed(0)} MB`);
// Percent for ordinary gaps; a ratio (e.g. 389×) once the gap is 300% or more, because those are easier to read.
const fmtPct = (v) => {
  if (v == null) return '—';
  if (v >= 300) return `×${(1 + v / 100).toFixed(0)} (+${v.toFixed(0)}%)`;
  return `${v > 0 ? '+' : ''}${v.toFixed(0)}%`;
};

// Describes the sandbox results from the data, so the text cannot drift from the numbers.
function summarizeEngines(data) {
  const worst = {};
  for (const [sizeLabel, perEngine] of Object.entries(data.results)) {
    for (const key of ['mount', 'find_all', 'replace_all', 'edit_per_op']) {
      const cm = perEngine.codemirror?.metrics?.[key]?.median;
      const others = ['monaco', 'ace'].map((e) => perEngine[e]?.metrics?.[key]?.median).filter((v) => v != null);
      if (cm == null || !others.length) continue;
      const fastestOther = Math.min(...others);
      const pct = percentDiff(fastestOther, cm);
      if (pct > 0 && (!worst[key] || pct > worst[key].pct)) worst[key] = { sizeLabel, pct };
    }
  }
  const names = { mount: 'opening', find_all: 'counting matches', replace_all: 'replace-all', edit_per_op: 'per-character editing' };
  const parts = Object.entries(worst).map(([key, w]) => `${names[key]} at ${w.sizeLabel} is ${fmtPct(w.pct)} slower than the faster of Monaco or Ace`);
  const headline = parts.length
    ? `Largest gaps where Wrytrove's engine (CodeMirror 6) is slower than the faster of Monaco or Ace: ${parts.join('; ')}.`
    : 'In this run, CodeMirror 6 was not slower than the faster of Monaco or Ace on any measured operation.';
  return `What this means: ${headline} Gaps under about 20% can be run-to-run noise, so repeat the run before quoting them.`;
}

const lines = [];
const push = (...xs) => lines.push(...xs);

push(
  '# Benchmark comparison',
  '',
  '<!-- Generated by benchmarks/compare.mjs from benchmarks/results/*.json. Do not edit by hand; rerun the scripts. -->',
  '',
  'This page compares Wrytrove with other editors using the same synthetic inputs. It has two parts, and they answer different questions:',
  '',
  '1. **Editor engines, one sandbox (measured here).** Wrytrove\'s editor core (CodeMirror 6) against Monaco and Ace on the same Linux machine. This shows how the engine itself performs. It does not include Wrytrove\'s toolbar, sidebar, file I/O, or Tauri/WebView2 layer.',
  '2. **Desktop products, Windows (run by the maintainer).** Wrytrove against Notepad++, Notepads, VS Code and Zed on the same Windows machine. This is the comparison that matters for users. It is only filled in after someone runs `npm run benchmark:products` on Windows.',
  '',
  'How to read the percentages: **"Wrytrove vs X" = (Wrytrove − X) ÷ X × 100.** Negative means Wrytrove is lower (faster, or uses less memory). Positive means Wrytrove is higher (slower, or uses more memory). Lower is better for every metric here.',
  '',
);

// ---- Part 1: engines ---------------------------------------------------------------------------
push('## 1. Editor engines (sandbox, measured)', '');
if (!engines) {
  push('_No results yet. Run `npm run benchmark:engines`._', '');
} else {
  const env = engines.environment;
  // Only the Chromium build changes between runs, so record it.
  push(
    `Run: ${engines.generatedAt.slice(0, 10)} · ${env.platform} (${env.arch}) · ${env.cpu} × ${env.logicalCpus} logical · ${env.memoryGiB} GiB RAM · Node ${env.node} · ${env.browser}.`,
    `Method: ${engines.method.measuredRuns} measured runs after 1 warm-up, fresh editor per run, median shown. ${engines.method.notes}`,
    '',
    'Monaco and Ace are other open-source editors, so they are reference engines, not competitor products. The sandbox is a Linux VM, so absolute numbers will differ from a Windows PC. The percentages within one run are the useful signal.',
    'Caveat on editing: CodeMirror updates its DOM synchronously for each edit, while Monaco and Ace defer rendering to a later frame. The per-edit figure therefore includes more rendering work for CodeMirror than for the other two. It is not a keystroke-latency measurement; that needs a browser input test.',
    '',
    '',
  );
  const metricRows = [
    ['mountMs', 'Open (create editor and load text)', 'mount', fmtMs],
    ['findMs', 'Count all matches of a literal string', 'find_all', fmtMs],
    ['replaceMs', 'Replace all matches', 'replace_all', fmtMs],
    ['editMs', 'Insert one character mid-document (per edit)', 'edit_per_op', (v) => (v == null ? '—' : `${v.toFixed(3)} ms`)],
  ];
  for (const [sizeLabel, perEngine] of Object.entries(engines.results)) {
    const fixture = engines.fixtures.find((f) => f.label === sizeLabel);
    push(`### ${sizeLabel} (${fixture ? (fixture.bytes / 1048576).toFixed(2) : '?'} MiB synthetic UTF-8, ${perEngine.codemirror?.needleMatches ?? '?'} matches)`, '');
    push('| Operation | Wrytrove engine (CodeMirror 6) | Monaco | Ace | Wrytrove vs Monaco | Wrytrove vs Ace |', '| --- | ---: | ---: | ---: | ---: | ---: |');
    for (const [, label, key, fmt] of metricRows) {
      const cm = perEngine.codemirror?.metrics?.[key]?.median;
      const mo = perEngine.monaco?.metrics?.[key]?.median;
      const ac = perEngine.ace?.metrics?.[key]?.median;
      push(`| ${label} | ${fmt(cm)} | ${fmt(mo)} | ${fmt(ac)} | ${fmtPct(percentDiff(mo, cm))} | ${fmtPct(percentDiff(ac, cm))} |`);
    }
    push('');
  }
  const correct = Object.values(engines.results).every((p) => Object.values(p).every((e) => e.replacedCorrectly));
  push(
    `Correctness check (per run: matches found > 0, replace-all count equals it, and no needle remains afterwards): **${correct ? 'passed for every engine and size' : 'FAILED for at least one — see results JSON'}**.`,
    '',
    summarizeEngines(engines),
    '',
  );
}

// ---- Part 2: products (Windows) -----------------------------------------------------------------
push('## 2. Desktop products (Windows, maintainer-run)', '');
if (!products) {
  push(
    '_Not run yet._ To fill this in, on a Windows PC with the apps installed:',
    '',
    '```powershell',
    'copy benchmarks\\product\\products.example.json benchmarks\\product\\products.local.json',
    '# edit products.local.json: set "machine" and each product\'s "exe" path, then close all app windows',
    'npm ci',
    'npm run benchmark:products',
    'npm run benchmark:compare',
    '```',
    '',
    'Results from different PCs are not comparable with each other. Only compare products within one run on one machine.',
    '**Status of the Windows harness:** written and checked with a dry run on Linux only. The PowerShell probe has not yet run on Windows, so expect to fix small issues on the first real run.',
    '',
  );
} else {
  const valid = Object.entries(products.products);
  push(
    `Machine: **${products.machine}** · ${products.environment.platform} · ${products.environment.cpu} × ${products.environment.logicalCpus} logical · ${products.environment.memoryGiB} GiB RAM · run ${products.generatedAt.slice(0, 10)}.`,
    `Method: ${products.method.measuredRuns} measured runs after 1 warm-up per scenario. ${products.method.readyDefinition}`,
    '',
  );
  const scenarioIds = ['startup', ...products.fixtures.map((f) => `open-${f.label}`)];
  const wrytrove = products.products.wrytrove;
  for (const scenario of scenarioIds) {
    push(`### ${scenario === 'startup' ? 'Startup (no file)' : `Open ${scenario.replace('open-', '')} synthetic file`}`, '');
    push('| Product | Ready (median) | p95 | Memory, working set | Memory, private | Valid runs | Wrytrove vs this product (ready / memory) |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: |');
    for (const [id, p] of valid) {
      const s = p.scenarios[scenario];
      const sum = s?.summary;
      const preliminary = !s || s.validRuns < 5;
      const readyPct = wrytrove && id !== 'wrytrove' ? fmtPct(percentDiff(p.scenarios[scenario]?.summary?.readyMs.median, wrytrove.scenarios[scenario]?.summary?.readyMs.median)) : '';
      const memPct = wrytrove && id !== 'wrytrove' ? fmtPct(percentDiff(p.scenarios[scenario]?.summary?.workingSetMB.median, wrytrove.scenarios[scenario]?.summary?.workingSetMB.median)) : '';
      push(
        `| ${p.name}${preliminary ? ' *(preliminary)*' : ''} | ${fmtMs(sum?.readyMs.median)} | ${fmtMs(sum?.readyMs.p95)} | ${fmtMB(sum?.workingSetMB.median)} | ${fmtMB(sum?.privateMB.median)} | ${s ? `${s.validRuns}/${s.totalRuns}` : '—'} | ${readyPct || '—'} / ${memPct || '—'} |`,
      );
    }
    push('');
  }
  push(
    'Rows marked *(preliminary)* have fewer than 5 valid runs and must not be quoted as results. A run is invalid when the app exited early (for example, it handed the file to an already open window) or did not reach input-idle within the timeout.',
    '',
  );
}

// ---- Manual workloads and limits --------------------------------------------------------------
push(
  '## Not measured yet',
  '',
  '- **Typing latency, scrolling, tab switching, Markdown preview update.** These need a UI driver and a human check on each product. They are not in the automated harness yet.',
  '- **Files above 20 MiB.** The synthetic set stops at 20 MiB, Wrytrove\'s current limit. Larger files (100 and 500 MiB in issue #65) need a separate fixture plan.',
  '- **Save, crash recovery, and session restore timings.**',
  '- **Warm and cold start split.** The harness runs warm-up trials but does not clear OS caches between runs.',
  '- **Browser build (sandbox run).** The engine run used Chromium 131 from an npm package, because the Playwright browser download was blocked in the sandbox. Playwright\'s own build may differ, so compare percentages within a run, not absolute times between runs.',
  '- **Competitor claims.** No product is "faster" or "lighter" from one run. Issue #65 requires paired runs on named hardware before any such claim is published.',
  '',
);

writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${outPath}`);
